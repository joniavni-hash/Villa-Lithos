#!/usr/bin/env python3
"""Build the Lovable/Supabase deployment set: merge src/ into one module
supabase/functions/_shared/engine.ts and rewrite the edge functions to import it.
Usage: python3 -I scripts/build-lovable-bundle.py OUT_DIR
Verify afterwards with deno check and an equivalence run against src/ (see README)."""
import glob, os, re, sys
O = sys.argv[1]
ORDER = ['pipeline/types.ts', 'config/villa.ts', 'scoring/weights.ts', 'scoring/budget.ts', 'scoring/ebn.ts', 'scoring/score.ts',
         'discovery/normalize.ts', 'discovery/queryGenerator.ts', 'insights/rescoring.ts', 'insights/learning.ts',
         'outreach/generator.ts', 'ai/prompts.ts']
found = sorted(os.path.relpath(os.path.join(dp, f), 'src') for dp, _, fs in os.walk('src') for f in fs if f.endswith('.ts'))
assert sorted(ORDER) == found, f'engine file list changed: {found}'
out = ['// Villa Lithos Influencer Finder engine, single-module build of influencer-finder/src for Supabase edge functions.',
       '// Generated by scripts/build-lovable-bundle.py from the tested sources. Do not edit here; edit src/ and rebuild.', '']
for f in ORDER:
    s = open('src/' + f).read()
    s = re.sub(r"^import (type )?\{[^}]*\} from '\.{1,2}/[^']+';\n", '', s, flags=re.M)
    assert not re.search(r"^import .* from '\.", s, re.M), f
    out += [f'// ===== {f} =====', s.strip() + '\n']
os.makedirs(f'{O}/supabase/functions/_shared', exist_ok=True)
open(f'{O}/supabase/functions/_shared/engine.ts', 'w').write('\n'.join(out))
for p in glob.glob('supabase/functions/*/index.ts'):
    s = re.sub(r"from '\.\./_shared/engine/[^']+'", "from '../_shared/engine.ts'", open(p).read())
    os.makedirs(f'{O}/' + os.path.dirname(p), exist_ok=True); open(f'{O}/' + p, 'w').write(s)
for p in ['supabase/functions/_shared/clients.ts', 'supabase/functions/_shared/mappers.ts']:
    open(f'{O}/' + p, 'w').write(re.sub(r"from '\./engine/[^']+'", "from './engine.ts'", open(p).read()))
print(f'built {O}')
