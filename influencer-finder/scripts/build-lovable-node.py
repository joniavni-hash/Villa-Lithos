#!/usr/bin/env python3
"""Build the server-side port for a Lovable TanStack Start project (Node-style runtime, process.env).
The edge functions are not rewritten by hand: each Deno.serve callback becomes `export async function handle(req)`,
Deno.env.get becomes process.env, and the Supabase admin client and user check use the clients Lovable generates
(@/integrations/supabase/client.server), which handle the new opaque Supabase API keys.
Usage: python3 -I scripts/build-lovable-node.py OUT_DIR    -> OUT_DIR/src/server/lithos/**"""
import glob, os, re, subprocess, sys, tempfile
O = sys.argv[1]
with tempfile.TemporaryDirectory() as t:
    subprocess.run([sys.executable, '-I', 'scripts/build-lovable-bundle.py', t], check=True, stdout=subprocess.DEVNULL)
    F = f'{t}/supabase/functions'
    D = f'{O}/src/server/lithos'; os.makedirs(f'{D}/handlers', exist_ok=True)
    hdr = '// Generated by influencer-finder/scripts/build-lovable-node.py from the tested Deno sources. Do not edit; change the source and rebuild.\n'
    open(f'{D}/engine.ts', 'w').write(open(f'{F}/_shared/engine.ts').read())

    c = open(f'{F}/_shared/clients.ts').read()
    c = c.replace("import { createClient, type SupabaseClient } from 'https://esm.sh/@supabase/supabase-js@2.45.4';",
                  "import type { SupabaseClient } from '@supabase/supabase-js';\nimport { supabaseAdmin } from '@/integrations/supabase/client.server';\n\nconst env = (k: string): string | undefined => process.env[k];")
    c, n1 = re.subn(r"export function adminClient\(\): SupabaseClient \{\n.*?\n\}\n",
                    "export function adminClient(): SupabaseClient {\n  return supabaseAdmin as unknown as SupabaseClient;\n}\n", c, flags=re.S)
    c, n2 = re.subn(r"  const anon = createClient\([^\n]*\n  const \{ data, error \} = await anon\.auth\.getUser\(\);",
                    "  const { data, error } = await supabaseAdmin.auth.getUser(token);", c)
    c = c.replace("Deno.env.get(", "env(")
    assert n1 == 1 and n2 == 1 and 'Deno' not in c.replace('Deno sources', '') and 'createClient' not in c, (n1, n2)
    open(f'{D}/clients.server.ts', 'w').write(hdr + c)

    m = open(f'{F}/_shared/mappers.ts').read().replace("from './engine.ts'", "from './engine'")
    assert 'Deno' not in m
    open(f'{D}/mappers.server.ts', 'w').write(hdr + m)

    names = []
    for p in sorted(glob.glob(f'{F}/*/index.ts')):
        name = p.split('/')[-2]; names.append(name)
        s = open(p).read()
        s = s.replace("from '../_shared/clients.ts'", "from '../clients.server'").replace("from '../_shared/engine.ts'", "from '../engine'").replace("from '../_shared/mappers.ts'", "from '../mappers.server'")
        i = s.index('Deno.serve(async (req) => {')
        j = i + len('Deno.serve(async (req) => ')
        depth = 0
        for k in range(j, len(s)):
            if s[k] == '{': depth += 1
            elif s[k] == '}':
                depth -= 1
                if depth == 0: break
        assert s[k + 1:k + 3] == ');', (name, s[k:k + 5])
        s = s[:i] + 'export async function handle(req: Request): Promise<Response> ' + s[j:k + 1] + s[k + 3:]
        assert 'Deno' not in s, name
        open(f'{D}/handlers/{name}.server.ts', 'w').write(hdr + s)
    idx = hdr + ''.join(f"import {{ handle as {n.replace('-', '_')} }} from './handlers/{n}.server';\n" for n in names)
    idx += '\n/** POST /api/lithos/<name> dispatch table. Each handler checks the bearer token itself. */\nexport const LITHOS_HANDLERS: Record<string, (req: Request) => Promise<Response>> = {\n'
    idx += ''.join(f"  '{n}': {n.replace('-', '_')},\n" for n in names) + '};\n'
    open(f'{D}/index.server.ts', 'w').write(idx)
print(f'built {O}/src/server/lithos: engine, clients, mappers, {len(names)} handlers')
